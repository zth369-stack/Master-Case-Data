/**
 * Utility to generate court bundle affidavit citation index for lawyers
 */
export function generateCourtAffidavitBundleIndex(docs: CourtEvidentiaryMetadataRecord[]): string {
  const timestamp = new Date().toUTCString();
  let text = `========================================================================================\n`;
  text += `IN THE HIGH COURT OF MALAYA AT KUALA LUMPUR\n`;
  text += `COMMERCIAL & PROBATE DIVISIONS\n`;
  text += `MASTER AFFIDAVIT IN SUPPORT - COMPREHENSIVE EVIDENTIARY EXHIBIT BUNDLE INDEX\n`;
  text += `COMPILED & VERIFIED PURSUANT TO EVIDENCE ACT 1950 (ACT 56) SECTIONS 65B & 90A\n`;
  text += `DATE OF COMPILATION: ${timestamp}\n`;
  text += `PRINCIPAL SUBJECT: KAVINATH A/L GANESAN (NRIC: 960906-08-5839)\n`;
  text += `========================================================================================\n\n`;

  docs.forEach((doc, idx) => {
    text += `ITEM #${idx + 1}: ${doc.exhibitNumber} - ${doc.documentTitle}\n`;
    text += `  • COURT FORUM: ${doc.courtOrJudicialForum}\n`;
    text += `  • EXACT LOCATION: ${doc.exactCourtLocation}\n`;
    text += `  • FILING / DOCKET REF: ${doc.courtDocketOrFilingRef}\n`;
    text += `  • EXTRACTION COORDINATES: ${doc.bundleExtractionCoordinates}\n`;
    text += `  • SOURCE AUTHORITY: ${doc.sourceDataAuthority}\n`;
    text += `  • ISSUANCE DATE: ${doc.issuanceDate}\n`;
    text += `  • STATUTORY ADMISSIBILITY: ${doc.statutoryAdmissibilityRule}\n`;
    text += `  • CRYPTOGRAPHIC SHA-256 HASH: ${doc.sha256VerificationHash}\n`;
    text += `  • SUMMARY PROOF: ${doc.summaryFindings}\n`;
    text += `----------------------------------------------------------------------------------------\n`;
  });

  text += `\n[END OF COURT EXTRACTION BUNDLE INDEX]\n`;
  return text;
}
